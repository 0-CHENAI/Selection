const AUTO_API_KEY_CONNECTION_NAME = /^Selection Backend \(API Key\)(?: (\d+))?$/

export function providerConnectionLabel(piAuthProvider?: string | null): string | null {
  const key = piAuthProvider?.trim()
  if (!key) return null
  return PI_PROVIDER_CONNECTION_LABELS[key] ?? titleCaseProviderKey(key)
}

function titleCaseProviderKey(key: string): string {
  return key
    .split('-')
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ')
}

/** Hostname only. The path and port stay out of the connection title. */
export function connectionHostnameLabel(baseUrl?: string | null): string | null {
  const trimmed = baseUrl?.trim()
  if (!trimmed) return null
  try {
    const hostname = new URL(trimmed).hostname
    return hostname || null
  } catch {
    return null
  }
}

function isLoopbackBaseUrl(baseUrl?: string | null): boolean {
  const hostname = connectionHostnameLabel(baseUrl)
  if (!hostname) return false
  const normalized = hostname.startsWith('[') && hostname.endsWith(']')
    ? hostname.slice(1, -1)
    : hostname
  return normalized === 'localhost' || normalized === '127.0.0.1' || normalized === '::1'
}

export function isAutoGeneratedApiKeyConnectionName(name?: string | null): boolean {
  return AUTO_API_KEY_CONNECTION_NAME.test(name?.trim() ?? '')
}

/**
 * New connections always receive a default title. An existing connection is
 * renamed only while it still carries the generic template name.
 */
export function shouldAssignApiKeyConnectionName(currentName: string, isNewConnection: boolean): boolean {
  return isNewConnection || isAutoGeneratedApiKeyConnectionName(currentName)
}

export function defaultApiKeyConnectionName(input: {
  piAuthProvider?: string | null
  baseUrl?: string | null
  isCustomEndpoint: boolean
  /** Keyless loopback, already decided by custom-endpoint setup. */
  localModelName?: string | null
}): string | null {
  if (input.localModelName?.trim()) return input.localModelName.trim()
  if (isOrderGatewayUrl(input.baseUrl)) return ORDER_CONNECTION_NAME
  if (input.baseUrl?.toLowerCase().includes('manifest.build')) return 'Manifest'
  if (input.isCustomEndpoint) return connectionHostnameLabel(input.baseUrl)
  return providerConnectionLabel(input.piAuthProvider)
}

/**
 * First connection keeps the brand. The next free "Name N" starts at 2.
 * `except` drops one stored copy of the connection's current title so a
 * re-save does not collide with itself.
 */
export function allocateUniqueConnectionName(
  base: string,
  existingNames: readonly string[],
  options?: { except?: string },
): string {
  const used = [...existingNames]
  if (options?.except) {
    const index = used.indexOf(options.except)
    if (index >= 0) used.splice(index, 1)
  }
  const taken = new Set(used)
  if (!taken.has(base)) return base
  let suffix = 2
  while (taken.has(`${base} ${suffix}`)) suffix += 1
  return `${base} ${suffix}`
}

/** Name to persist, or undefined when the stored title must stay as-is. */
export function resolveSetupConnectionName(input: {
  isNewConnection: boolean
  currentName: string
  existingNames: readonly string[]
  piAuthProvider?: string | null
  baseUrl?: string | null
  isCustomEndpoint: boolean
  localModelName?: string | null
}): string | undefined {
  if (!shouldAssignApiKeyConnectionName(input.currentName, input.isNewConnection)) return undefined
  const base = defaultApiKeyConnectionName(input)
  if (!base) return undefined
  return allocateUniqueConnectionName(base, input.existingNames, {
    except: input.isNewConnection ? undefined : input.currentName,
  })
}

export function migrateAutoGeneratedApiKeyConnectionNames(
  connections: Array<{
    name: string
    piAuthProvider?: string | null
    baseUrl?: string | null
    providerType?: string | null
    authType?: string | null
  }>,
): boolean {
  const names = connections.map((connection) => connection.name)
  let changed = false
  for (const connection of connections) {
    if (!isAutoGeneratedApiKeyConnectionName(connection.name)) continue
    const localModelName = connection.authType === 'none' && isLoopbackBaseUrl(connection.baseUrl)
      ? 'Local Model'
      : undefined
    const base = defaultApiKeyConnectionName({
      piAuthProvider: connection.piAuthProvider,
      baseUrl: connection.baseUrl,
      isCustomEndpoint: connection.providerType === 'pi_compat',
      localModelName,
    })
    if (!base) continue
    const next = allocateUniqueConnectionName(base, names, { except: connection.name })
    if (next === connection.name) continue
    const index = names.indexOf(connection.name)
    if (index >= 0) names[index] = next
    connection.name = next
    changed = true
  }
  return changed
}
