/**
 * Default names for API-key connections.
 *
 * The setup template used to persist "Selection Backend (API Key)" and, when
 * the slug already existed, "Selection Backend (API Key) 2". Known Pi providers
 * were then rewritten to "Selection Backend (Google AI Studio)". Providers
 * missing from that map (DeepSeek and later brands) kept the template name,
 * so the connection list showed "Selection Backend (API Key) 3" above a
 * "DeepSeek · api.deepseek.com" subtitle.
 *
 * New connections use the provider brand (DeepSeek, ORDER). A custom endpoint
 * with no brand uses the URL hostname. A second connection with the same
 * label becomes "DeepSeek 2". Names the user edited are left alone. Startup
 * migration rewrites only the generic template name, including its numeric
 * suffix — not "Selection Backend (OpenAI)" and not a custom title.
 */

import { isOrderGatewayUrl, ORDER_CONNECTION_NAME } from './order-gateway.ts'

