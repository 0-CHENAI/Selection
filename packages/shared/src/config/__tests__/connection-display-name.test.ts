import { describe, expect, it } from 'bun:test'
import {
  allocateUniqueConnectionName,
  isAutoGeneratedApiKeyConnectionName,
  migrateAutoGeneratedApiKeyConnectionNames,
  resolveSetupConnectionName,
} from '../connection-display-name.ts'

describe('API key connection names', () => {
  it('names a new DeepSeek connection after the provider, ignoring the slug suffix', () => {
    expect(resolveSetupConnectionName({
      isNewConnection: true,
      currentName: 'Selection Backend (API Key) 3',
      existingNames: ['Selection Backend (API Key)', 'Selection Backend (API Key) 2'],
      piAuthProvider: 'deepseek',
      baseUrl: 'https://api.deepseek.com',
      isCustomEndpoint: false,
    })).toBe('DeepSeek')
  })

  it('adds the next free number only when that provider name is taken', () => {
    expect(resolveSetupConnectionName({
      isNewConnection: true,
      currentName: 'Selection Backend (API Key)',
      existingNames: ['DeepSeek', 'DeepSeek 3'],
      piAuthProvider: 'deepseek',
      isCustomEndpoint: false,
    })).toBe('DeepSeek 2')

    expect(allocateUniqueConnectionName('DeepSeek', ['DeepSeek', 'DeepSeek 2'])).toBe('DeepSeek 3')
  })

  it('names ORDER and a custom host, and keeps a second ORDER distinct', () => {
    expect(resolveSetupConnectionName({
      isNewConnection: true,
      currentName: 'Selection Backend (API Key)',
      existingNames: [],
      piAuthProvider: 'openai',
      baseUrl: 'https://order.ai.jxepdi.top/v1',
      isCustomEndpoint: true,
    })).toBe('ORDER')

    expect(resolveSetupConnectionName({
      isNewConnection: true,
      currentName: 'Selection Backend (API Key) 2',
      existingNames: ['ORDER'],
      piAuthProvider: 'openai',
      baseUrl: 'https://order.ai.jxepdi.top/v1',
      isCustomEndpoint: true,
    })).toBe('ORDER 2')

    expect(resolveSetupConnectionName({
      isNewConnection: true,
      currentName: 'Selection Backend (API Key)',
      existingNames: [],
      piAuthProvider: 'openai',
      baseUrl: 'https://gateway.example.com/v1',
      isCustomEndpoint: true,
    })).toBe('gateway.example.com')
  })

  it('names a keyless loopback Local Model and a Manifest host Manifest', () => {
    expect(resolveSetupConnectionName({
      isNewConnection: true,
      currentName: 'Selection Backend (API Key)',
      existingNames: ['Local Model'],
      baseUrl: 'http://127.0.0.1:11434/v1',
      isCustomEndpoint: true,
      localModelName: 'Local Model',
    })).toBe('Local Model 2')

    expect(resolveSetupConnectionName({
      isNewConnection: true,
      currentName: 'Selection Backend (API Key)',
      existingNames: [],
      baseUrl: 'https://app.manifest.build/v1',
      isCustomEndpoint: true,
    })).toBe('Manifest')
  })

  it('does not replace a name the user edited, or an older branded automatic name', () => {
    expect(isAutoGeneratedApiKeyConnectionName('Selection Backend (API Key)')).toBe(true)
    expect(isAutoGeneratedApiKeyConnectionName('Selection Backend (API Key) 12')).toBe(true)
    expect(isAutoGeneratedApiKeyConnectionName('Selection Backend (OpenAI)')).toBe(false)
    expect(isAutoGeneratedApiKeyConnectionName('Selection Backend (Google AI Studio)')).toBe(false)
    expect(isAutoGeneratedApiKeyConnectionName('工作 DeepSeek')).toBe(false)

    expect(resolveSetupConnectionName({
      isNewConnection: false,
      currentName: '工作 DeepSeek',
      existingNames: ['工作 DeepSeek'],
      piAuthProvider: 'deepseek',
      isCustomEndpoint: false,
    })).toBeUndefined()

    expect(resolveSetupConnectionName({
      isNewConnection: false,
      currentName: 'Selection Backend (Google AI Studio)',
      existingNames: ['Selection Backend (Google AI Studio)'],
      piAuthProvider: 'google',
      isCustomEndpoint: false,
    })).toBeUndefined()
  })

  it('renames an existing generic API-key title when that connection is saved again', () => {
    expect(resolveSetupConnectionName({
      isNewConnection: false,
      currentName: 'Selection Backend (API Key) 3',
      existingNames: ['ChatGPT Plus', 'Selection Backend (API Key) 3', 'DeepSeek'],
      piAuthProvider: 'deepseek',
      isCustomEndpoint: false,
    })).toBe('DeepSeek 2')
  })

  it('migrates only generic API-key titles and keeps user and older branded titles', () => {
    const connections = [
      {
        name: 'Selection Backend (API Key)',
        providerType: 'pi',
        authType: 'api_key',
        piAuthProvider: 'deepseek',
        baseUrl: 'https://api.deepseek.com',
      },
      {
        name: 'Selection Backend (API Key) 2',
        providerType: 'pi',
        authType: 'api_key',
        piAuthProvider: 'deepseek',
      },
      {
        name: '工作 DeepSeek',
        providerType: 'pi',
        authType: 'api_key',
        piAuthProvider: 'deepseek',
      },
      {
        name: 'Selection Backend (OpenAI)',
        providerType: 'pi',
        authType: 'api_key',
        piAuthProvider: 'openai',
      },
      {
        name: 'Selection Backend (API Key) 4',
        providerType: 'pi_compat',
        authType: 'api_key_with_endpoint',
        piAuthProvider: 'openai',
        baseUrl: 'https://order.ai.jxepdi.top/v1',
      },
      {
        name: 'Selection Backend (API Key) 5',
        providerType: 'pi_compat',
        authType: 'api_key_with_endpoint',
        piAuthProvider: 'openai',
        baseUrl: 'https://gateway.example.com/v1',
      },
    ]

    expect(migrateAutoGeneratedApiKeyConnectionNames(connections)).toBe(true)
    expect(connections.map((connection) => connection.name)).toEqual([
      'DeepSeek',
      'DeepSeek 2',
      '工作 DeepSeek',
      'Selection Backend (OpenAI)',
      'ORDER',
      'gateway.example.com',
    ])
    expect(migrateAutoGeneratedApiKeyConnectionNames(connections)).toBe(false)
  })
})
