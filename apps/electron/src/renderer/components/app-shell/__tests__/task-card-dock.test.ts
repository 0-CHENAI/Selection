import { describe, expect, test } from 'bun:test'
import { readFileSync } from 'node:fs'

function read(path: string): string {
  return readFileSync(new URL(path, import.meta.url), 'utf8')
}

describe('task card dock', () => {
  test('docks the capsule and the scroll button in the composer toolbar row', () => {
    const chat = read('../ChatDisplay.tsx')
    const zone = read('../input/ChatInputZone.tsx')
    const badges = read('../ActiveOptionBadges.tsx')
    expect(chat).toContain('<TaskProgressCard')
    expect(chat).toContain('placement="toolbar"')
    expect(chat).toContain('placement="overlay"')
    expect(chat).toContain('shellMaxWidth={slot.shellMaxWidth}')
    expect(chat).toContain('toolbarCenter=')
    expect(chat).toContain('scrollInToolbar')
    expect(chat).toContain('taskScrollFused')
    expect(chat).toContain('showScrollToBottom={showScrollToBottom}')
    expect(chat).not.toContain('showScrollToBottom && (taskCard.visible || taskCardPresent)')
    expect(chat).toContain('showScrollToBottom && !taskScrollFused')
    expect(chat).toContain('absolute bottom-3 left-1/2')
    expect(chat).toContain('data-testid="chat-scroll-to-bottom"')
    expect(chat).toContain('todoRail={todoRailForTurn({')
    expect(chat).toContain('docked: taskCard.visible || taskCardPresent')
    expect(chat).toContain('superseded: userTurnAfterList')
    expect(chat).toContain('useSessionTaskCard')
    expect(chat).toContain('sessionKey={activeSessionId}')
    expect(chat).toContain('listSeed={latestTodo.listSeed}')
    expect(chat).toContain('taskListSeed({')
    expect(chat).not.toContain('data-task-card-clearance')
    expect(chat).not.toContain('TASK_CARD_CAPSULE_CLEARANCE')
    expect(chat).toContain('userTurnAfterList')
    expect(chat).toContain('generationEnded:')
    expect(chat).not.toContain('onDismiss=')
    expect(chat).not.toContain('beforeInput={')
    expect(zone).toContain('{beforeInput}')
    expect(zone).toContain('center={toolbarCenter}')
    expect(zone).toContain('CHAT_CLASSES.composerColumn')
    expect(badges).toContain('data-toolbar-row')
    expect(badges).toContain('data-toolbar-label')
    expect(badges).toContain('toolbarCapsuleFit')
    expect(badges).toContain('<FolderOpen')
    expect(badges).toContain('<PermissionModeIcon')
    expect(badges).toContain("iconsOnly && \"hidden\"")
    const cardAt = chat.indexOf('<TaskProgressCard')
    const scrollAt = chat.indexOf('key="scroll-to-bottom"')
    const inputAt = chat.indexOf('<ChatInputZone')
    expect(cardAt).toBeGreaterThan(0)
    expect(cardAt).toBeLessThan(scrollAt)
    expect(scrollAt).toBeLessThan(inputAt)
  })
})
